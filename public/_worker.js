const fullLoadPoints = 550;
const pricePerPoint = 1.82;
const minimumPrice = 100;
const quarterLoadThreshold = fullLoadPoints * 0.25; // 137.5
const quarterLoadPrice = 250;

function calculatePrice(cart) {
  const totalVolume = cart.reduce((sum, item) => sum + item.volume, 0);
  const totalItemPrice = cart.reduce((sum, item) => sum + item.price, 0);
  const highestItemPrice = cart.reduce((max, item) => Math.max(max, item.price), 0);

  const volumePrice = totalVolume * pricePerPoint;

  // ✅ NEW: If cart is empty, total must be 0
  if (totalVolume === 0) {
    return { finalPrice: 0, totalVolume };
  }

  // ✅ 1) Single high-value item rule
  if (cart.length === 1 && highestItemPrice > quarterLoadPrice) {
    return { finalPrice: highestItemPrice, totalVolume };
  }

  // ✅ 2) UNDER 1/4 load logic
  if (totalVolume < quarterLoadThreshold) {
    if (totalItemPrice < quarterLoadPrice) {
      // Still under $250 – use higher of min or item price
      return { finalPrice: Math.max(minimumPrice, totalItemPrice), totalVolume };
    } else {
      // Crossed $250 → switch entirely to volume-based pricing
      return { finalPrice: volumePrice, totalVolume };
    }
  }

  // ✅ 3) 1/4 load and above – tier snapping for FIRST truck only
  const fullLoads = Math.floor(totalVolume / fullLoadPoints);
  const remainder = totalVolume % fullLoadPoints;
  const remainderCost = remainder * pricePerPoint;

  if (fullLoads === 0) {
    const tiers = [
      { point: quarterLoadThreshold, price: 250 },
      { point: fullLoadPoints * 0.5, price: 500 },
      { point: fullLoadPoints * 0.75, price: 750 },
      { point: fullLoadPoints, price: 1000 },
    ];

    for (const tier of tiers) {
      if (totalVolume > tier.point && totalVolume <= tier.point + 10) {
        return { finalPrice: tier.price, totalVolume };
      }
    }

    // If not within rounding zone → fall back to raw volume
    return { finalPrice: volumePrice, totalVolume };
  }

  // ✅ 4) MULTIPLE TRUCKS → flat 1000 per full + cubic on remainder
  return {
    finalPrice: fullLoads * 1000 + remainderCost,
    totalVolume,
  };
}

// ✅ Needed for load bar labeling and UI
function getLoadLabel(volume) {
  if (volume === 0) return 'Empty';
  const loadNum = Math.floor(volume / fullLoadPoints) + 1;
  const segment = volume % fullLoadPoints;
  if (segment === 0) return `Load ${loadNum}`;
  if (segment <= fullLoadPoints * 0.25) return `Load ${loadNum} - 1/4`;
  if (segment <= fullLoadPoints * 0.5) return `Load ${loadNum} - 1/2`;
  if (segment <= fullLoadPoints * 0.75) return `Load ${loadNum} - 3/4`;
  return `Load ${loadNum} - Full`;
}


const norm = (s = "") => String(s).toLowerCase().trim();
const slug = (s = "") => norm(s).replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

function lev(a = "", b = "") {
  const m = a.length, n = b.length;
  if (!m) return n;
  if (!n) return m;
  const dp = Array.from({ length: m + 1 }, () => Array(n + 1).fill(0));
  for (let i = 0; i <= m; i++) dp[i][0] = i;
  for (let j = 0; j <= n; j++) dp[0][j] = j;
  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      dp[i][j] = Math.min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + cost);
    }
  }
  return dp[m][n];
}

function parseDims(t = "") {
  const s = t.toLowerCase().replace(/,/g, " ");
  let m = s.match(/(\d+(?:\.\d+)?)\s*(?:ft|feet)['"]?\s*[x×]\s*(\d+(?:\.\d+)?)\s*(?:ft|feet)['"]?\s*[x×]\s*(\d+(?:\.\d+)?)\s*(?:ft|feet)/);
  if (m) return { L:+m[1], W:+m[2], H:+m[3], unit:"ft" };
  m = s.match(/(\d+(?:\.\d+)?)\s*(?:in|inch|inches)['"]?\s*[x×]\s*(\d+(?:\.\d+)?)\s*(?:in|inch|inches)['"]?\s*[x×]\s*(\d+(?:\.\d+)?)\s*(?:in|inch|inches)/);
  if (m) return { L:+m[1], W:+m[2], H:+m[3], unit:"in" };
  m = s.match(/(\d+(?:\.\d+)?)\s*[x×]\s*(\d+(?:\.\d+)?)\s*[x×]\s*(\d+(?:\.\d+)?)/);
  if (m) return { L:+m[1], W:+m[2], H:+m[3], unit:"in" };
  return null;
}

function dimsToCuFt(d) {
  if (!d || !d.L || !d.W || !d.H) return null;
  return d.unit === "ft" ? d.L*d.W*d.H : (d.L/12)*(d.W/12)*(d.H/12);
}

function flattenCatalog(nested = []) {
  const flat = [];
  for (const cat of nested) {
    const category = cat.category || "";
    for (const it of (cat.items || [])) {
      flat.push({
        id: slug(category + "-" + (it.name || "Item")),
        name: it.name || "Item",
        price: Number(it.price || 0),
        volume: Number(it.volume || 0),
        category
      });
    }
  }
  return flat;
}

const ITEMS = flattenCatalog(itemData);

const SYNONYMS = [
  ["couch","sofa"],
  ["love seat","loveseat"],
  ["tv","television"],
  ["fridge","refrigerator"],
  ["coffee table","table - coffee"],
  ["table coffee","table - coffee"]
];

function bestCatalogMatch(raw) {
  const q0 = norm(raw);
  const q = q0.replace(/\bcoffee table\b/g, "table - coffee");
  let best = { score: Infinity, item: null };
  for (const it of ITEMS) {
    const a = norm(it.name);
    if (a.includes(q) || q.includes(a)) {
      const score = Math.abs(a.length - q.length);
      if (score < best.score) best = { score, item: it };
      continue;
    }
    let qSyn = q;
    for (const pair of SYNONYMS) {
      const from = pair[0], to = pair[1];
      qSyn = qSyn.split(from).join(to);
    }
    const d = lev(qSyn, a);
    const score = d / Math.max(1, Math.max(qSyn.length, a.length));
    if (score < best.score) best = { score, item: it };
  }
  return best.score <= 0.45 ? best.item : null;
}

function corsHeaders(extra = {}) {
  return {
    "Content-Type": "application/json",
    "Cache-Control": "no-store",
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Headers": "Content-Type",
    "Access-Control-Allow-Methods": "GET,POST,OPTIONS",
    "Access-Control-Expose-Headers": "X-AI,X-Mode,X-OpenAI-Status",
    ...extra
  };
}

function json(data, status = 200, extra = {}) {
  return new Response(JSON.stringify(data), { status, headers: corsHeaders(extra) });
}

function openAIHeaders(env) {
  const h = {
    "Content-Type": "application/json",
    "Authorization": "Bearer " + env.OPENAI_API_KEY
  };
  if (env.OPENAI_PROJECT) h["OpenAI-Project"] = String(env.OPENAI_PROJECT).trim();
  if (env.OPENAI_ORG) h["OpenAI-Organization"] = String(env.OPENAI_ORG).trim();
  return h;
}

async function callOpenAI(env, messages, jsonMode = true) {
  const body = {
    model: env.OPENAI_MODEL || "gpt-4o-mini",
    temperature: 0,
    messages
  };
  if (jsonMode) body.response_format = { type: "json_object" };

  const r = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: openAIHeaders(env),
    body: JSON.stringify(body)
  });

  const text = await r.text();
  if (!r.ok) {
    const err = new Error("OpenAI request failed: " + r.status);
    err.status = r.status;
    err.detail = text.slice(0, 500);
    throw err;
  }

  let payload;
  try { payload = JSON.parse(text); } catch { payload = {}; }
  return payload?.choices?.[0]?.message?.content || "";
}

async function routeWithAI(env, messages) {
  const catalogNames = ITEMS.map(i => i.name).slice(0, 160).join(", ");
  const system = [
    "You are the Junk Buddies junk-removal assistant.",
    "Decide each turn as chat, estimate, or both.",
    'Return STRICT JSON: {"mode":"chat|estimate|both","chat":"string or null","items":[{"name":"string","qty":number,"dims":"optional raw dims"}]}.',
    "Rules:",
    '- Use "chat" only for a general question with no junk items.',
    '- Use "estimate" when items, quantities, sizes, or dimensions are listed.',
    '- Use "both" when the user asks a question and also lists items.',
    "- Keep chat answers brief, 1–2 sentences.",
    "- Preserve quantities and important size/type details such as queen, king, sectional piece count, commercial/residential, etc.",
    "- Prefer catalog wording when a clear match exists.",
    "- Understand common furniture-set language by decomposing sets into real catalog components instead of treating the set as one vague object.",
    "- If the user says bed set and does not list pieces, interpret it as mattress + matching bed frame + matching bed base/foundation; preserve Twin/Full/Queen/King size when stated.",
    "- If the user says bedroom set and does not list pieces, interpret it as bed frame + dresser + 2 nightstands; if a mattress/base is explicitly mentioned, include it too. Preserve stated bed size.",
    "- If the user says living room set and does not list pieces, interpret it as sofa/couch + loveseat + coffee table. If the user lists the pieces, use their explicit list instead.",
    "- Do not double-count pieces that the user already named separately.",
    "- Never invent or state a dollar price. The website calculates pricing.",
    "Catalog examples: " + catalogNames
  ].join("\n");

  const content = await callOpenAI(env, [
    { role: "system", content: system },
    ...messages.map(m => ({
      role: m.role === "assistant" ? "assistant" : "user",
      content: String(m.content || "")
    }))
  ]);

  let obj = {};
  try { obj = JSON.parse(content || "{}"); } catch {}
  const mode = ["chat","estimate","both"].includes(obj.mode) ? obj.mode : "estimate";
  const chat = typeof obj.chat === "string" && obj.chat.trim() ? obj.chat.trim() : null;
  const items = Array.isArray(obj.items) ? obj.items.map(it => ({
    name: String(it.name || "").trim(),
    qty: Math.max(1, parseInt(it.qty || 1, 10)),
    dims: typeof it.dims === "string" ? it.dims : null
  })).filter(it => it.name) : [];
  return { mode, chat, items };
}

async function extractItemsWithAI(env, text) {
  const catalogNames = ITEMS.map(i => i.name).slice(0, 160).join(", ");
  const content = await callOpenAI(env, [
    {
      role: "system",
      content: 'Extract junk-removal items. Reply ONLY with JSON {"items":[{"name":"string","qty":number,"dims":"optional raw dims"}]}. Preserve quantities and useful size/type details. Prefer catalog wording when clear. Understand sets: bed set means mattress + matching bed frame + matching bed base/foundation when pieces are not listed; bedroom set means bed frame + dresser + 2 nightstands by default; living room set means sofa/couch + loveseat + coffee table by default. Preserve stated bed size, use explicit listed pieces instead of defaults, and do not double-count. Never invent prices.'
    },
    { role: "system", content: "Catalog examples: " + catalogNames },
    { role: "user", content: text }
  ]);
  let obj = {};
  try { obj = JSON.parse(content || "{}"); } catch {}
  return Array.isArray(obj.items) ? obj.items.map(it => ({
    name: String(it.name || "").trim(),
    qty: Math.max(1, parseInt(it.qty || 1, 10)),
    dims: typeof it.dims === "string" ? it.dims : null
  })).filter(it => it.name) : [];
}

async function estimateCuFtWithAI(env, label) {
  const content = await callOpenAI(env, [
    {
      role: "system",
      content: "Return a conservative realistic typical cubic-foot estimate for one household or junk-removal item. JSON only. Do not return a price."
    },
    {
      role: "user",
      content: 'Item: ' + label + '\nReturn {"cuft": number} with cuft between 1 and 300.'
    }
  ]);
  let obj = {};
  try { obj = JSON.parse(content || "{}"); } catch {}
  const cuft = Number(obj.cuft || 15);
  return Math.max(1, Math.min(300, Number.isFinite(cuft) ? cuft : 15));
}

async function rowsToCart(env, rows) {
  const pointsPerCuFt = Number(env.POINTS_PER_CUFT || 1);
  const cart = [];
  for (const row of rows) {
    const qty = Math.max(1, Number(row.qty || 1));
    const matched = bestCatalogMatch(row.name);
    if (matched) {
      cart.push({
        id: matched.id,
        name: matched.name,
        qty,
        volume: matched.volume * qty,
        price: matched.price * qty
      });
      continue;
    }

    const dims = row.dims ? parseDims(row.dims) : parseDims(row.name);
    let cuft = dimsToCuFt(dims);
    if (cuft == null) cuft = await estimateCuFtWithAI(env, row.name);
    const points = Math.max(1, Math.min(300, cuft * pointsPerCuFt)) * qty;
    cart.push({
      id: "unlisted-" + slug(row.name),
      name: row.name,
      qty,
      volume: points,
      price: 0
    });
  }
  return cart;
}

async function handleChat(request, env) {
  if (!env.OPENAI_API_KEY) {
    return json(
      { error: "openai_key_missing", detail: "OPENAI_API_KEY is not available to the Cloudflare worker." },
      503,
      { "X-AI": "off" }
    );
  }

  const body = await request.json().catch(() => ({}));
  const messages = Array.isArray(body.messages) ? body.messages : [];
  const lastRaw = messages[messages.length - 1]?.content || "";

  let routed;
  try {
    routed = await routeWithAI(env, messages);
  } catch (err) {
    return json(
      { error: "openai_error", detail: err.detail || err.message || "OpenAI failed" },
      502,
      { "X-AI": "off", "X-OpenAI-Status": String(err.status || "error") }
    );
  }

  if (routed.mode === "chat" && routed.chat) {
    return json({
      reply: routed.chat,
      parsed: { cart: [], finalPrice: 0, totalVolume: 0, loadLabel: "Empty" }
    }, 200, { "X-AI": "on", "X-Mode": routed.mode });
  }

  let rows = routed.items;
  if (!rows.length && lastRaw) {
    try { rows = await extractItemsWithAI(env, lastRaw); } catch {}
  }

  if (!rows.length) {
    return json({
      reply: 'Tell me items like “2 couches + treadmill + queen mattress”. I’ll price them using our catalog.',
      parsed: { cart: [], finalPrice: 0, totalVolume: 0, loadLabel: "Empty" }
    }, 200, { "X-AI": "on", "X-Mode": "estimate" });
  }

  let cart;
  try {
    cart = await rowsToCart(env, rows);
  } catch (err) {
    return json(
      { error: "openai_volume_error", detail: err.detail || err.message || "Volume estimate failed" },
      502,
      { "X-AI": "off", "X-OpenAI-Status": String(err.status || "error") }
    );
  }

  const { finalPrice, totalVolume } = calculatePrice(cart);
  const loadLabel = getLoadLabel(totalVolume);
  const bullets = cart.map(li => "• " + li.qty + "× " + li.name).join("\n");
  const estimateText = bullets + "\n\nEstimated total: $" + finalPrice.toFixed(2);
  const reply = routed.mode === "both" && routed.chat
    ? routed.chat + "\n\n" + estimateText
    : estimateText;

  return json({
    reply,
    parsed: {
      cart,
      finalPrice: Math.round(finalPrice * 100) / 100,
      totalVolume,
      loadLabel
    }
  }, 200, { "X-AI": "on", "X-Mode": routed.mode });
}

async function handleHealth(env) {
  if (!env.OPENAI_API_KEY) {
    return json({ ok:false, hasOpenAIKey:false, error:"OPENAI_API_KEY missing" }, 200, { "X-AI":"off" });
  }
  try {
    const content = await callOpenAI(env, [
      { role:"system", content:"Return JSON only." },
      { role:"user", content:'Return {"ping":true} exactly.' }
    ]);
    return json({ ok:true, hasOpenAIKey:true, model:env.OPENAI_MODEL || "gpt-4o-mini", sample:content.slice(0,80) }, 200, {
      "X-AI":"on",
      "X-OpenAI-Status":"200"
    });
  } catch (err) {
    return json({
      ok:false,
      hasOpenAIKey:true,
      status:err.status || "error",
      detail:err.detail || err.message
    }, 200, {
      "X-AI":"off",
      "X-OpenAI-Status":String(err.status || "error")
    });
  }
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (request.method === "OPTIONS" && url.pathname.startsWith("/api/")) {
      return new Response(null, { status:204, headers:corsHeaders() });
    }

    if (url.pathname === "/api/envcheck") {
      return json({
        runtime:"cloudflare-pages-worker",
        hasOpenAIKey:Boolean(env.OPENAI_API_KEY),
        hasOpenAIProject:Boolean(env.OPENAI_PROJECT),
        hasOpenAIOrg:Boolean(env.OPENAI_ORG),
        model:env.OPENAI_MODEL || "gpt-4o-mini",
        pointsPerCuFt:env.POINTS_PER_CUFT || "default:1"
      }, 200, { "X-AI": env.OPENAI_API_KEY ? "on" : "off" });
    }

    if (url.pathname === "/api/aihealth") {
      return handleHealth(env);
    }

    if (url.pathname === "/api/chat") {
      if (request.method !== "POST") {
        return json({ error:"Method not allowed" }, 405, { "X-AI": env.OPENAI_API_KEY ? "on" : "off" });
      }
      return handleChat(request, env);
    }

    return env.ASSETS.fetch(request);
  }
};
